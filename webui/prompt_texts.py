    "- 已确认的筛选条件（薪资/经验/学历/规模/融资/行业）是硬约束：岗位结构化标签或 JD 明确写"
    "'必须/要求/限'的硬性要求与已选条件冲突时，必须 match=false，不得只写 caveats 后仍判 match；"
    "JD 中'优先/加分/熟悉/了解'类软性要求不受此限。\n"
    "- 判断是参考不是法律：匹配从宽只适用于候选人没有约束的维度；第一层已选字段冲突即 match=false，"
    "画像和隐藏画像字段不得推翻；画像只能放宽未选择的维度。\n"
    "- 以候选人自己的主业方向为锚：画像明确写了方向（如开发、运营、设计、产品、销售、培训等），"
    "岗位属于同一职业链路才可 match；明显跨链路的岗位默认 match=false。\n"
    "- 画像未明确写方向时，从核心技能和经历判断主业；岗位明显不属于该链路且候选人能力支撑不了，"
    "默认 match=false。\n"
    "- 用户明确写'不限/都可以/接受xx'时，按用户意愿放宽，覆盖默认不匹配。\n"
    "- 岗位类别不能只按标题判断，以 JD 主责为准；混合岗（如售前、解决方案）按主责归入对应链路。\n"
